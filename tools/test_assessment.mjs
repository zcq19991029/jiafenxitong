import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context=vm.createContext({});vm.runInContext(fs.readFileSync('assessment.js','utf8'),context);
const A=context.JFDT_ASSESSMENT;let passed=0;
function check(name,value){assert.ok(value,name);passed++;console.log('PASS',name);}
const members=[{name:'甲',sid:'991'},{name:'乙',sid:'992'},{name:'丙',sid:'993'}];
const cls={id:'test',groups:[{no:1,members}],roster:[...members,{name:'未分组',sid:'994'}]};
const raw=[{...members[0],gno:1,total:10,groupScore:5,project:5,personal:0},{...members[1],gno:1,total:10,groupScore:5,project:5,personal:0},{...members[2],gno:1,total:5,groupScore:5,project:0,personal:0}];
let rows=A.rows(cls,[],raw);
check('ties receive equal top learning assignment',rows[0].learning===80&&rows[1].learning===80&&rows[0].rank===1&&rows[1].rank===1);
check('competition ranking skips positions occupied by ties',rows[2].rawRank===3&&rows[2].learning===40);
check('unassigned roster students remain in assessment',rows.length===4&&rows[3].gno===0&&rows[3].learning===20);
check('missing attendance is a full attendance estimate without invented records',rows[0].attendance===20&&rows[0].recorded===0&&!cls.attendance);
check('forty percent regular plus sixty percent exam threshold',rows[0].regular===100&&rows[0].contribution===40&&rows[0].needed===33.4);
let lessons=[{attendance:{'sid:991':{status:'late',loss:1}}},{attendance:{'sid:991':{status:'truant',loss:3},'sid:992':{status:'leave',loss:0}}}];
rows=A.rows(cls,lessons,raw);let first=rows.find(m=>m.sid==='991');
check('attendance deducts lesson units from twenty points',first.loss===4&&first.attendance===16.7&&first.recorded===2);
check('attendance never mutates raw classroom points',first.total===10&&raw[0].total===10);
cls.assessmentSettings={...A.settings(cls),totalLessons:2,late:8};
rows=A.rows(cls,lessons,raw);
check('historical attendance retains stored deduction when rules change',rows.find(m=>m.sid==='991').loss===4);
check('attendance cannot fall below zero',rows.find(m=>m.sid==='991').attendance===0);
cls.examScores={'sid:992':50};rows=A.rows(cls,lessons,raw);
check('actual final exam computes weighted overall grade',rows.find(m=>m.sid==='992').final===70);
let zero=A.rows(cls,[],[]);
check('all zero raw scores do not manufacture eighty learning points',zero.every(m=>m.learning===0));
let single=A.rows({groups:[{no:1,members:[members[0]]}],roster:[]},[],[raw[0]]);
check('single positive student receives eighty learning points',single[0].learning===80);
cls.assessmentSettings.passScore=100;rows=A.rows(cls,lessons,raw);
check('impossible exam target remains above one hundred and is not clamped',rows.find(m=>m.sid==='991').needed>100);
check('custom deductions use the configured rule',A.deduction('custom_x',{customRules:[{id:'custom_x',name:'自定义',loss:2}]})===2);
check('leave and present default to zero deduction',A.deduction('leave',A.settings({}))===0&&A.deduction('present',A.settings({}))===0);
console.log(`Assessment formulas: ${passed} passed, 0 failed`);
